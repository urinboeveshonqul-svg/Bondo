-- -----------------------------------------------------------------------------
-- orders
-- -----------------------------------------------------------------------------
-- No insert policy for anyone. `place_order` is `security definer` and is the
-- only writer; adding one here would reopen every hole the function exists to
-- close.
--
-- No delete policy for anyone, including super admin. Cancelling is an update.
create policy "orders: a customer reads their own"
  on public.orders for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "orders: orders.read sees every order"
  on public.orders for select
  to authenticated
  using (public.has_permission('orders.read'));

create policy "orders: orders.update maintains them"
  on public.orders for update
  to authenticated
  using (public.has_permission('orders.update'))
  with check (public.has_permission('orders.update'));

-- -----------------------------------------------------------------------------
-- order_items
-- -----------------------------------------------------------------------------
-- Readable exactly when the parent order is. Written only by `place_order`.
create policy "order_items: readable with the order"
  on public.order_items for select
  to authenticated
  using (
    exists (
      select 1 from public.orders o
      where o.id = order_items.order_id
        and (o.user_id = (select auth.uid()) or public.has_permission('orders.read'))
    )
  );

-- -----------------------------------------------------------------------------
-- order_status_history
-- -----------------------------------------------------------------------------
-- A customer sees their own order move; that is the tracking page. Staff see
-- everything. Nobody writes — the trigger does, and the append-only guard
-- refuses updates and deletes even to `service_role`.
create policy "order_status_history: readable with the order"
  on public.order_status_history for select
  to authenticated
  using (
    exists (
      select 1 from public.orders o
      where o.id = order_status_history.order_id
        and (o.user_id = (select auth.uid()) or public.has_permission('orders.read'))
    )
  );

-- -----------------------------------------------------------------------------
-- product_reviews
-- -----------------------------------------------------------------------------
-- Reviews are public: a shopper who has not bought anything still reads them.
create policy "product_reviews: anyone reads reviews of published products"
  on public.product_reviews for select
  to anon, authenticated
  using (
    exists (
      select 1 from public.products p
      where p.id = product_reviews.product_id
        and p.deleted_at is null
        and p.status = 'active'
        and p.visibility = 'public'
        and p.published_at is not null
        and p.published_at <= now()
    )
  );

-- **This policy is the feature.** Everything the brief asks for — verified
-- buyer, delivered order, one per purchased product — is here, where a Server
-- Action cannot forget it and a leaked anon key cannot get round it.
create policy "product_reviews: a delivered buyer may review what they bought"
  on public.product_reviews for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1
      from public.orders o
      join public.order_items oi on oi.order_id = o.id
      where o.id = product_reviews.order_id
        and o.user_id = (select auth.uid())
        and o.status = 'delivered'
        and oi.product_id = product_reviews.product_id
    )
  );

-- An author may correct their own wording. They may not move it to another
-- product or another order, which `with check` re-asserting the join prevents.
create policy "product_reviews: an author edits their own"
  on public.product_reviews for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1
      from public.orders o
      join public.order_items oi on oi.order_id = o.id
      where o.id = product_reviews.order_id
        and o.user_id = (select auth.uid())
        and o.status = 'delivered'
        and oi.product_id = product_reviews.product_id
    )
  );

create policy "product_reviews: an author deletes their own"
  on public.product_reviews for delete
  to authenticated
  using (user_id = (select auth.uid()));

