-- Explicit and least-privilege, matching 20260801000900 (ADR-30): a mistaken
-- policy still meets a closed second gate.
--
-- Note what `anon` gets: reviews, and the right to call `place_order`. It holds
-- no table privilege on `orders` or `order_items` at all, so a guest checkout
-- works and a guest cannot read back what anybody else ordered.
grant select on public.orders to authenticated;
grant update on public.orders to authenticated;
grant select on public.order_items to authenticated;
grant select on public.order_status_history to authenticated;

grant select on public.product_reviews to anon, authenticated;
grant insert, update, delete on public.product_reviews to authenticated;

grant execute on function public.place_order(
  text, text, text, jsonb, text, text, text, public.locale
) to anon, authenticated;

-- The sequence is driven from inside a definer function, so no client role needs
-- it. Stated rather than left implicit, because a missing sequence grant is a
-- classic silent checkout failure.
revoke all on sequence public.order_reference_seq from anon, authenticated;
